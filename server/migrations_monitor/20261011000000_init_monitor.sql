-- Tiered system monitoring (data/monitor.db, separate from sqlite.db and not backed up).
-- All three tiers share one shape: 5s rows are aggregated from 1s samples, 1m/1h rows
-- are rolled up from the tier below. Stat columns hold min/avg/max of their bucket;
-- sample_count weights averages across tiers and makes downtime visible.

CREATE TABLE monitor_5s (
	bucket_ms     INTEGER PRIMARY KEY, -- bucket start (UTC epoch ms)
	sample_count  INTEGER NOT NULL,
	sys_cpu_min REAL,
	sys_cpu_avg REAL,
	sys_cpu_max REAL,
	app_cpu_min REAL,
	app_cpu_avg REAL,
	app_cpu_max REAL,
	sys_mem_min REAL,
	sys_mem_avg REAL,
	sys_mem_max REAL,
	app_mem_min REAL,
	app_mem_avg REAL,
	app_mem_max REAL,
	swap_min REAL,
	swap_avg REAL,
	swap_max REAL,
	load1_min REAL,
	load1_avg REAL,
	load1_max REAL,
	cpu_temp_min REAL,
	cpu_temp_avg REAL,
	cpu_temp_max REAL,
	net_rx_min REAL,
	net_rx_avg REAL,
	net_rx_max REAL,
	net_tx_min REAL,
	net_tx_avg REAL,
	net_tx_max REAL,
	app_read_min REAL,
	app_read_avg REAL,
	app_read_max REAL,
	app_write_min REAL,
	app_write_avg REAL,
	app_write_max REAL,
	disk_used     REAL,
	disk_free_gib REAL,
	throttled     INTEGER -- Pi get_throttled bits 0-3, OR-ed over the bucket; NULL off-Pi
);

